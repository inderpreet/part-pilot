namespace InventoryTracker.Data.Entities;

/// <summary>
/// A job that needs a known list of parts (a bill of materials, <see cref="Lines"/>) to produce
/// <see cref="TargetUnits"/> units. Archived (<see cref="IsActive"/> = false) once it has builds; a project with no
/// builds may be deleted. Never reserves stock: its status is calculated live from stock and purchase orders.
/// </summary>
public class Project : IHasTimestamps, IHasRowVersion
{
    public const int NameMaxLength = 100;
    public const int NumberMaxLength = 30;
    public const int DescriptionMaxLength = 500;
    public const int NotesMaxLength = 2000;

    /// <summary>Largest target (and largest single build), so quantity per unit x units stays inside a <c>long</c> with room to spare.</summary>
    public const int MaxTargetUnits = 100_000;

    /// <summary>The database key every relationship inside the app uses.</summary>
    public int Id { get; set; }

    public required string Name { get; set; }

    /// <summary>
    /// The project number (<c>PRJ-2026-0001</c>): generated by <c>ProjectService</c> unless the user typed one, unique
    /// case-insensitively, and changed only by an Admin. The key outside systems use; never a foreign key.
    /// </summary>
    public required string Number { get; set; }

    public string? Description { get; set; }

    /// <summary>How many units the project is meant to produce; at least 1.</summary>
    public int TargetUnits { get; set; } = 1;

    public string? Notes { get; set; }

    public bool IsActive { get; set; } = true;

    public long RowVersion { get; set; }

    public DateTime CreatedAt { get; set; }

    public DateTime UpdatedAt { get; set; }

    public List<BomLine> Lines { get; set; } = [];

    public List<ProjectBuild> Builds { get; set; } = [];
}

/// <summary>One part of a project's bill of materials. At most one line per product per project.</summary>
public class BomLine : IHasTimestamps
{
    public const int NoteMaxLength = 200;

    /// <summary>Largest quantity per unit (keeps quantity x units x cost comfortably inside a <c>long</c>).</summary>
    public const int MaxQuantityPerUnit = 1_000_000;

    public long Id { get; set; }

    public int ProjectId { get; set; }

    public Project? Project { get; set; }

    public int ProductId { get; set; }

    public Product? Product { get; set; }

    /// <summary>How many of the product one unit of the project needs; at least 1.</summary>
    public int QuantityPerUnit { get; set; }

    public string? Note { get; set; }

    public DateTime CreatedAt { get; set; }

    public DateTime UpdatedAt { get; set; }
}

/// <summary>
/// A recorded build: <see cref="Units"/> units of the project were made and their parts were issued from stock.
/// Append-only (no <c>UpdatedAt</c>); the issue rows it caused are found through their reference text (decision D18).
/// </summary>
public class ProjectBuild : IHasCreatedAt
{
    public const int NoteMaxLength = 500;

    public long Id { get; set; }

    public int ProjectId { get; set; }

    public Project? Project { get; set; }

    /// <summary>Units built; at least 1.</summary>
    public int Units { get; set; }

    public required string UserId { get; set; }

    public ApplicationUser? User { get; set; }

    public string? Note { get; set; }

    public DateTime CreatedAt { get; set; }
}
